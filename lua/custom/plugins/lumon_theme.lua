-- The `lumon` colorscheme itself lives in two places:
--   * `lua/lumon/palette.lua`  -- the colors
--   * `colors/lumon.lua`       -- the aether.nvim variant that applies them
-- This spec only installs the engine and selects the variant.

return {
  {
    'bjarneo/aether.nvim',
    branch = 'v3',
    name = 'aether',
    priority = 1000,
    opts = {
      transparent = false,
    },
    config = function(_, opts)
      require('aether').setup(opts)
      vim.cmd.colorscheme 'lumon'
      -- Hot reload registers itself from aether.setup/load as of v3; no call needed.
    end,
  },
}
